export type ComponentStatus = "stable" | "beta" | "experimental" | "planned";

export interface ComponentMeta {
  slug: string;
  name: string;
  category: string;
  description: string;
  longDescription: string;
  status: ComponentStatus;
  tags: string[];
  capabilities: string[];
  whenToUse: string[];
  whenNotToUse: string[];
  properties: ComponentProperty[];
  methods: ComponentMethod[];
  events: ComponentEvent[];
  defaults: Record<string, unknown>;
}

export interface ComponentProperty {
  name: string;
  type: string;
  default: string;
  description: string;
}

export interface ComponentMethod {
  signature: string;
  description: string;
  returns?: string;
}

export interface ComponentEvent {
  name: string;
  payload: string;
  description: string;
}

export interface CategoryMeta {
  slug: string;
  name: string;
  description: string;
  icon: string; // lucide icon name
  capabilities: string[];
  useCases: string[];
}

